"""Allowlisting egress proxy for sandboxed runs.

A run with ``network = true`` and a non-empty ``allow_hosts`` is placed on an *internal*
Docker network (no route to the outside) together with a small proxy container. The proxy
also joins a normal *upstream* network and is the sandbox's only way out: it accepts plain
HTTP and ``CONNECT`` and answers ``403`` for any host not on the list. Because the sandbox
is not attached to the upstream network, direct egress fails even if the sandbox ignores the
proxy environment variables — the topology, not the proxy alone, enforces the policy.

The proxy image is shared and content-addressed over the Dockerfile and the *template* of
the script (not the per-run host list); the per-run list is passed to the container through
``JANUS_PROXY_ALLOW_HOSTS``. It is built once and never removed.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import secrets
import shutil
import tempfile
from collections.abc import Sequence
from pathlib import Path
from types import TracebackType

import docker
from docker.errors import BuildError, DockerException, ImageNotFound
from docker.models.containers import Container

from janus.sandbox.settings import SandboxSettings

PROXY_PORT = 8888

_ENV_ALLOW_HOSTS = "JANUS_PROXY_ALLOW_HOSTS"
_IMAGE_PREFIX = "janus-sandbox-proxy"
_INTERNAL_PREFIX = "janus-sbx"
_UPSTREAM_PREFIX = "janus-sbx-up"
_PROXY_PREFIX = "janus-sbx-proxy"
_CONTEXT_PREFIX = "janus-proxy-build-"
_LABEL = {"janus.sandbox.proxy": "1"}
_ALLOW_HOSTS_PLACEHOLDER = "__ALLOW_HOSTS_JSON__"
_PORT_PLACEHOLDER = "__PROXY_PORT__"


class ProxyError(RuntimeError):
    """Raised when the egress proxy or its networks cannot be prepared."""


# The proxy script is rendered into the image and into each run. It uses only the standard
# library (the image is ``python:3.12-slim``) and is deliberately explicit: it rejects
# malformed request lines, caps the header size, and never forwards to an unparsed host.
_PROXY_SCRIPT_TEMPLATE = r'''"""Allowlisting egress proxy. Generated by Janus; do not edit.

Accepts plain HTTP (absolute-URI request lines) and CONNECT tunnels, checks the target host
against the allow list, and answers 403 Forbidden for anything not listed.

The host-matching rules below MUST stay in sync with
janus.sandbox.allowlist.host_allowed.
"""
from __future__ import annotations

import asyncio
import json
import os
import sys

ALLOW_HOSTS = __ALLOW_HOSTS_JSON__

_PORT = __PROXY_PORT__
_MAX_HEADER_BYTES = 65536
_CHUNK = 65536


def _normalise(host):
    host = host.strip().lower()
    if host.endswith("."):
        host = host[:-1]
    return host


def host_allowed(host):
    # Keep in sync with janus.sandbox.allowlist.host_allowed.
    host = _normalise(host)
    if not host:
        return False
    if not ALLOW_HOSTS:
        return True
    for entry in ALLOW_HOSTS:
        entry = _normalise(entry)
        if not entry:
            continue
        if entry.startswith("."):
            suffix = entry[1:]
            if suffix and (host == suffix or host.endswith(entry)):
                return True
        elif host == entry:
            return True
    return False


class _BadRequest(Exception):
    pass


async def _read_header(reader):
    data = bytearray()
    while b"\r\n\r\n" not in data:
        chunk = await reader.read(4096)
        if not chunk:
            if not data:
                return None
            raise _BadRequest("truncated request")
        data.extend(chunk)
        if len(data) > _MAX_HEADER_BYTES:
            raise _BadRequest("header too large")
    index = data.find(b"\r\n\r\n")
    raw = bytes(data[: index + 4])
    leftover = bytes(data[index + 4 :])
    line = raw.split(b"\r\n", 1)[0]
    return line.decode("latin-1"), raw, leftover


def _split_authority(target):
    if target.startswith("["):
        end = target.find("]")
        if end == -1:
            return None
        host = target[1:end]
        rest = target[end + 1 :]
        if not rest.startswith(":"):
            return None
        port = rest[1:]
        if not port.isdigit():
            return None
        return host, int(port)
    host, sep, port = target.rpartition(":")
    if not sep or not host or not port.isdigit():
        return None
    return host, int(port)


def _http_authority(target):
    from urllib.parse import urlsplit

    parts = urlsplit(target)
    if parts.scheme.lower() != "http" or not parts.hostname:
        return None
    return parts.hostname, (parts.port or 80)


async def _drain(writer):
    try:
        await writer.drain()
    except Exception:
        pass


def _close(writer):
    try:
        writer.close()
    except Exception:
        pass


async def _deny(writer):
    writer.write(b"HTTP/1.1 403 Forbidden\r\nConnection: close\r\nContent-Length: 0\r\n\r\n")
    await _drain(writer)


async def _bad_gateway(writer):
    writer.write(b"HTTP/1.1 502 Bad Gateway\r\nConnection: close\r\nContent-Length: 0\r\n\r\n")
    await _drain(writer)


async def _relay(reader, writer):
    try:
        while True:
            data = await reader.read(_CHUNK)
            if not data:
                break
            writer.write(data)
            await writer.drain()
    except Exception:
        pass
    finally:
        _close(writer)


async def _handle(reader, writer):
    try:
        parsed = await _read_header(reader)
    except _BadRequest as exc:
        print(f"janus-proxy: bad request: {exc}", flush=True)
        await _deny(writer)
        _close(writer)
        return
    if parsed is None:
        _close(writer)
        return
    request_line, raw, leftover = parsed
    parts = request_line.split(" ")
    if len(parts) != 3:
        print("janus-proxy: malformed request line", flush=True)
        await _deny(writer)
        _close(writer)
        return
    method, target = parts[0].upper(), parts[1]

    if method == "CONNECT":
        authority = _split_authority(target)
        if authority is None:
            print(f"janus-proxy: bad CONNECT target {target!r}", flush=True)
            await _deny(writer)
            _close(writer)
            return
        host, port = authority
        if not host_allowed(host):
            print(f"janus-proxy: denied CONNECT {host}:{port}", flush=True)
            await _deny(writer)
            _close(writer)
            return
        try:
            up_reader, up_writer = await asyncio.open_connection(host, port)
        except OSError as exc:
            print(f"janus-proxy: connect {host}:{port} failed: {exc}", flush=True)
            await _bad_gateway(writer)
            _close(writer)
            return
        writer.write(b"HTTP/1.1 200 Connection Established\r\n\r\n")
        await _drain(writer)
        await asyncio.gather(_relay(reader, up_writer), _relay(up_reader, writer))
        _close(writer)
        return

    authority = _http_authority(target)
    if authority is None:
        print(f"janus-proxy: bad HTTP target {target!r}", flush=True)
        await _deny(writer)
        _close(writer)
        return
    host, port = authority
    if not host_allowed(host):
        print(f"janus-proxy: denied {method} {host}:{port}", flush=True)
        await _deny(writer)
        _close(writer)
        return
    try:
        up_reader, up_writer = await asyncio.open_connection(host, port)
    except OSError as exc:
        print(f"janus-proxy: connect {host}:{port} failed: {exc}", flush=True)
        await _bad_gateway(writer)
        _close(writer)
        return
    up_writer.write(raw + leftover)
    await _drain(up_writer)
    await asyncio.gather(_relay(reader, up_writer), _relay(up_reader, writer))
    _close(writer)


def _load_hosts():
    raw = os.environ.get("JANUS_PROXY_ALLOW_HOSTS")
    if not raw:
        return ALLOW_HOSTS
    try:
        parsed = json.loads(raw)
    except ValueError:
        print("janus-proxy: invalid JANUS_PROXY_ALLOW_HOSTS", flush=True)
        sys.exit(2)
    if not isinstance(parsed, list):
        print("janus-proxy: JANUS_PROXY_ALLOW_HOSTS must be a list", flush=True)
        sys.exit(2)
    return parsed


async def main():
    global ALLOW_HOSTS
    ALLOW_HOSTS = _load_hosts()
    server = await asyncio.start_server(_handle, "0.0.0.0", _PORT)
    print(f"janus-proxy: listening on 0.0.0.0:{_PORT} allow={ALLOW_HOSTS}", flush=True)
    async with server:
        await server.serve_forever()


if __name__ == "__main__":
    asyncio.run(main())
'''


PROXY_DOCKERFILE = (
    "FROM python:3.12-slim\n"
    "COPY proxy.py /proxy.py\n"
    f"EXPOSE {PROXY_PORT}\n"
    'CMD ["python", "-u", "/proxy.py"]\n'
)


def render_proxy_script(allow_hosts: Sequence[str]) -> str:
    """Render the standalone proxy script with ``allow_hosts`` embedded as a JSON literal.

    The script runs in a ``python:3.12-slim`` container and uses only the standard library.
    The same host-matching rule lives in ``janus.sandbox.allowlist.host_allowed``; keep the
    two in sync.
    """
    hosts_json = json.dumps(list(allow_hosts))
    return _PROXY_SCRIPT_TEMPLATE.replace(_ALLOW_HOSTS_PLACEHOLDER, hosts_json).replace(
        _PORT_PLACEHOLDER, str(PROXY_PORT)
    )


def proxy_image_tag() -> str:
    """Content-addressed tag for the shared proxy image.

    Hashed over the Dockerfile and a canonical rendering of the script (an empty host list),
    so the tag is independent of any run's host list and the image is built once and reused.
    """
    digest = hashlib.sha256()
    digest.update(PROXY_DOCKERFILE.encode("utf-8"))
    digest.update(b"\0")
    digest.update(render_proxy_script(()).encode("utf-8"))
    digest.update(b"\0")
    return f"{_IMAGE_PREFIX}:{digest.hexdigest()[:12]}"


def _build_proxy_image(client: docker.DockerClient, tag: str) -> None:
    context = Path(tempfile.mkdtemp(prefix=_CONTEXT_PREFIX))
    try:
        (context / "Dockerfile").write_text(PROXY_DOCKERFILE, encoding="utf-8")
        (context / "proxy.py").write_text(render_proxy_script(()), encoding="utf-8")
        _image, logs = client.images.build(
            path=str(context),
            tag=tag,
            dockerfile="Dockerfile",
            pull=True,
            rm=True,
            labels=_LABEL,
        )
        for _line in logs:
            pass
    finally:
        shutil.rmtree(context, ignore_errors=True)


def ensure_proxy_image(client: docker.DockerClient, settings: SandboxSettings) -> str:
    """Build the shared proxy image when it is absent and return its tag.

    The image is content-addressed and shared, so it is never removed here. Any Docker
    failure is wrapped in :class:`ProxyError`.
    """
    del settings  # the tag depends only on the proxy sources
    tag = proxy_image_tag()
    try:
        client.images.get(tag)
        return tag
    except ImageNotFound:
        pass
    except DockerException as exc:
        raise ProxyError(f"proxy_image_unavailable: {exc}") from exc
    try:
        _build_proxy_image(client, tag)
    except (BuildError, DockerException) as exc:
        raise ProxyError(f"proxy_image_build_failed: {exc}") from exc
    return tag


def start_proxy(
    client: docker.DockerClient,
    settings: SandboxSettings,
    *,
    name: str,
    internal_network: str,
    upstream_network: str,
    allow_hosts: Sequence[str],
) -> Container:
    """Start the proxy detached on the internal network, then attach it upstream.

    ``network_mode`` is deliberately not used: the proxy needs to sit on two user-defined
    networks at once, which only the network API supports.
    """
    image = ensure_proxy_image(client, settings)
    try:
        container: Container = client.containers.run(
            image,
            name=name,
            detach=True,
            network=internal_network,
            environment={_ENV_ALLOW_HOSTS: json.dumps(list(allow_hosts))},
            mem_limit=f"{settings.proxy_memory_mb}m",
            pids_limit=settings.proxy_pids_limit,
            cap_drop=["ALL"],
            security_opt=["no-new-privileges"],
            labels=_LABEL,
        )
    except DockerException as exc:
        raise ProxyError(f"proxy_start_failed: {exc}") from exc
    try:
        client.networks.get(upstream_network).connect(container)
    except DockerException as exc:
        stop_proxy(container)
        raise ProxyError(f"proxy_upstream_failed: {exc}") from exc
    return container


def stop_proxy(container: Container) -> None:
    """Best-effort stop and remove of the proxy container."""
    with contextlib.suppress(DockerException):
        container.stop(timeout=5)
    with contextlib.suppress(DockerException):
        container.remove(force=True)


class ProxySession:
    """Owns the two networks and the proxy container for one run.

    Enter creates ``janus-sbx-<id>`` (internal), ``janus-sbx-up-<id>`` (upstream), and the
    proxy attached to both. Exit tears everything down, suppressing Docker errors so a
    failed teardown cannot mask the run's result.
    """

    def __init__(
        self,
        client: docker.DockerClient,
        settings: SandboxSettings,
        *,
        allow_hosts: Sequence[str],
        run_id: str | None = None,
    ) -> None:
        self._client = client
        self._settings = settings
        self._allow_hosts = tuple(allow_hosts)
        self._run_id = run_id or secrets.token_hex(6)
        self.internal_network = f"{_INTERNAL_PREFIX}-{self._run_id}"
        self.upstream_network = f"{_UPSTREAM_PREFIX}-{self._run_id}"
        self.proxy_host = f"{_PROXY_PREFIX}-{self._run_id}"
        self._proxy: Container | None = None

    def env(self) -> dict[str, str]:
        """The proxy environment variables to set on the sandbox container."""
        url = f"http://{self.proxy_host}:{self._settings.proxy_port}"
        return {
            "HTTP_PROXY": url,
            "HTTPS_PROXY": url,
            "http_proxy": url,
            "https_proxy": url,
        }

    def __enter__(self) -> ProxySession:
        try:
            self._client.networks.create(self.internal_network, internal=True, labels=_LABEL)
            self._client.networks.create(self.upstream_network, labels=_LABEL)
            self._proxy = start_proxy(
                self._client,
                self._settings,
                name=self.proxy_host,
                internal_network=self.internal_network,
                upstream_network=self.upstream_network,
                allow_hosts=self._allow_hosts,
            )
        except ProxyError:
            self._teardown()
            raise
        except DockerException as exc:
            self._teardown()
            raise ProxyError(f"proxy_setup_failed: {exc}") from exc
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        self._teardown()

    def _teardown(self) -> None:
        if self._proxy is not None:
            stop_proxy(self._proxy)
            self._proxy = None
        for network in (self.upstream_network, self.internal_network):
            with contextlib.suppress(DockerException):
                self._client.networks.get(network).remove()
